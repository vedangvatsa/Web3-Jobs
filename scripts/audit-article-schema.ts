/**
 * Audit Article / NewsArticle / ScholarlyArticle JSON-LD eligibility for published articles.
 * Usage: npm run audit:article-schema
 */
import fs from 'node:fs';
import path from 'node:path';
import matter from 'gray-matter';
import {
  buildArticleBreadcrumbStructuredData,
  buildArticleStructuredData,
  getArticleSchemaIssues,
  type ArticleStructuredDataInput,
} from '../src/lib/article-structured-data';

const siteUrl = 'https://hashtagweb3.com';
const articlesDir = path.join(process.cwd(), 'content/articles');
const NON_ARTICLE = new Set(['AGENTS.md', 'README.md']);
const SCHOLARLY = ['AI & The Future of Work', 'Web3 Career Guides'];

function loadArticles(): ArticleStructuredDataInput[] {
  const articles: ArticleStructuredDataInput[] = [];
  for (const fileName of fs.readdirSync(articlesDir)) {
    if (!fileName.endsWith('.md') || NON_ARTICLE.has(fileName)) continue;
    const slug = fileName.replace(/\.md$/, '');
    const { data } = matter(fs.readFileSync(path.join(articlesDir, fileName), 'utf8'));
    if (typeof data.title !== 'string' || !data.title) continue;
    const category = typeof data.category === 'string' && data.category ? data.category : 'General';
    const image =
      typeof data.image === 'string' && data.image && !data.image.includes('picsum.photos')
        ? data.image
        : category === 'News'
          ? 'https://hashtagweb3.com/og-news.png'
          : 'https://hashtagweb3.com/og-image-blog.png';
    const description =
      typeof data.description === 'string' && data.description ? data.description : 'No description provided.';
    articles.push({
      slug,
      title: data.title,
      description,
      category,
      image,
      publishedDate: typeof data.publishedDate === 'string' ? data.publishedDate : undefined,
      lastUpdated: typeof data.lastUpdated === 'string' ? data.lastUpdated : undefined,
      'data-ai-hint': typeof data['data-ai-hint'] === 'string' ? data['data-ai-hint'] : undefined,
    });
  }
  return articles;
}

function main() {
  const articles = loadArticles();
  const exclusionCounts: Record<string, number> = {};
  const byType: Record<string, number> = {};
  let eligible = 0;
  const rows: Array<{ slug: string; type: string; url: string; eligible: boolean; issues: string[] }> = [];

  for (const article of articles) {
    const issues = getArticleSchemaIssues(article);
    for (const issue of issues) exclusionCounts[issue] = (exclusionCounts[issue] || 0) + 1;
    const schema = buildArticleStructuredData(article, siteUrl);
    const breadcrumb = buildArticleBreadcrumbStructuredData(article, siteUrl);
    if (!breadcrumb.itemListElement?.length) throw new Error(`Breadcrumb missing for ${article.slug}`);
    if (schema) {
      eligible++;
      byType[String(schema['@type'])] = (byType[String(schema['@type'])] || 0) + 1;
    }
    const schemaType =
      article.category === 'News' ? 'NewsArticle' : SCHOLARLY.includes(article.category) ? 'ScholarlyArticle' : 'Article';
    rows.push({
      slug: article.slug,
      type: schemaType,
      url: `${siteUrl}/${article.slug}`,
      eligible: Boolean(schema),
      issues,
    });
  }

  const lines = [
    '# Article structured data audit',
    '',
    'Generated by `npm run audit:article-schema` against `content/articles/*.md`.',
    '',
    `${eligible} of ${articles.length} article pages emit Article, NewsArticle, or ScholarlyArticle JSON-LD. BreadcrumbList is emitted on every article detail page regardless.`,
    '',
    '## By schema type (eligible pages only)',
    '',
    '| @type | Pages |',
    '| --- | --- |',
    ...Object.entries(byType).map(([type, count]) => `| ${type} | ${count} |`),
    '',
    '## Exclusions',
    '',
    '| Reason | Pages |',
    '| --- | --- |',
    ...Object.entries(exclusionCounts).map(([reason, count]) => `| ${reason} | ${count} |`),
    '',
  ];

  const failing = rows.filter((row) => !row.eligible);
  if (failing.length) {
    lines.push('## Pages missing article JSON-LD', '', '| Article | Reasons |', '| --- | --- |');
    for (const row of failing) {
      lines.push(`| [${row.slug}](${row.url}) | ${row.issues.join(', ') || 'unknown'} |`);
    }
    lines.push('');
  }

  fs.writeFileSync(path.join(process.cwd(), 'content/articles/SCHEMA.md'), `${lines.join('\n')}\n`);
  fs.writeFileSync(
    path.join(process.cwd(), 'content/articles/schema-report.json'),
    `${JSON.stringify({ total: articles.length, eligible, exclusions: exclusionCounts, byType, articles: rows }, null, 2)}\n`,
  );
  console.log(`Article schema audit: ${eligible}/${articles.length} eligible. Exclusions: ${JSON.stringify(exclusionCounts)}`);
}

main();