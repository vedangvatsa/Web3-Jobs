/**
 * Offline JobPosting JSON-LD eligibility audit over jobs-runtime.json.
 * Full page description validation still requires rendered HTML (see test:job-schema).
 * Usage: npm run audit:job-posting-catalog
 */
import fs from 'node:fs';
import path from 'node:path';
import type { Job } from '../src/types';
import { buildJobPostingSchema } from '../src/lib/job-posting-schema';
import { getJobPostingLocation } from '../src/lib/job-posting-location';
import { jobAgeExclusionReason } from '../src/lib/job-age-policy.mjs';
const siteUrl = 'https://hashtagweb3.com';
const catalogPath = path.join(process.cwd(), 'public/data/jobs-runtime.json');
const representativeHtml =
  '<p>Responsibilities and requirements are listed on the employer career page linked from this posting.</p>';

function main() {
  const now = Date.now();
  const jobs: Job[] = JSON.parse(fs.readFileSync(catalogPath, 'utf8'));
  const locationCounts: Record<string, number> = {};
  const ageCounts: Record<string, number> = {};
  const emissionCounts: Record<string, number> = {};
  let locationEligible = 0;
  let schemaEligible = 0;

  for (const job of jobs) {
    const ageReason = jobAgeExclusionReason(job, now);
    const ageKey = ageReason || 'eligible-age';
    ageCounts[ageKey] = (ageCounts[ageKey] || 0) + 1;

    const location = getJobPostingLocation(job);
    const locKey = location.reason || (location.fields?.jobLocationType ? 'eligible-remote' : 'eligible-physical');
    locationCounts[locKey] = (locationCounts[locKey] || 0) + 1;
    if (!location.reason && !ageReason) locationEligible++;

    const built = buildJobPostingSchema({
      job,
      contentHtml: representativeHtml,
      descriptionIsFallback: false,
      siteUrl,
      now,
    });
    if (built.schema) {
      schemaEligible++;
      emissionCounts.eligible = (emissionCounts.eligible || 0) + 1;
    } else {
      for (const reason of built.reasons) emissionCounts[reason] = (emissionCounts[reason] || 0) + 1;
    }
  }

  const lines = [
    '# Google JobPosting schema audit (catalog)',
    '',
    'Generated by `npm run audit:job-posting-catalog` against `public/data/jobs-runtime.json`.',
    '',
    `[Google JobPosting documentation](https://developers.google.com/search/docs/appearance/structured-data/job-posting)`,
    '',
    `**${schemaEligible}** of **${jobs.length}** catalog jobs would emit JobPosting JSON-LD with representative on-page description HTML (see script).`,
    `**${locationEligible}** pass the location and age gates before description checks.`,
    '',
    'BreadcrumbList is always emitted on job detail pages. Suppressed jobs keep visible listings and application links.',
    '',
    '## Location gate (all catalog rows)',
    '',
    '| Result | Jobs |',
    '| --- | --- |',
    ...Object.entries(locationCounts)
      .sort((a, b) => b[1] - a[1])
      .map(([reason, count]) => `| ${reason} | ${count} |`),
    '',
    '## Age gate',
    '',
    '| Result | Jobs |',
    '| --- | --- |',
    ...Object.entries(ageCounts)
      .sort((a, b) => b[1] - a[1])
      .map(([reason, count]) => `| ${reason} | ${count} |`),
    '',
    '## Full emission (location + age + title + link + description stub)',
    '',
    '| Reason | Jobs |',
    '| --- | --- |',
    ...Object.entries(emissionCounts)
      .sort((a, b) => b[1] - a[1])
      .map(([reason, count]) => `| ${reason} | ${count} |`),
    '',
    'Address and remote-country gaps require employer location data in the feed, not inferred defaults.',
    '',
  ];

  fs.mkdirSync(path.join(process.cwd(), 'content/jobs'), { recursive: true });
  fs.writeFileSync(path.join(process.cwd(), 'content/jobs/SCHEMA.md'), `${lines.join('\n')}\n`);
  fs.writeFileSync(
    path.join(process.cwd(), 'content/jobs/schema-report.json'),
    `${JSON.stringify(
      {
        total: jobs.length,
        schemaEligible,
        locationEligible,
        locationCounts,
        ageCounts,
        emissionCounts,
        checkedAt: new Date(now).toISOString(),
      },
      null,
      2,
    )}\n`,
  );
  console.log(
    `JobPosting catalog audit: ${schemaEligible}/${jobs.length} eligible (location-only pass: ${locationEligible}). Emission blocks: ${JSON.stringify(
      Object.fromEntries(Object.entries(emissionCounts).filter(([k]) => k !== 'eligible')),
    )}`,
  );
}

main();